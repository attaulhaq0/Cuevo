import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import AxeBuilder from '@axe-core/playwright';
type Account = { role: string; email: string; password: string };
test('account access and school policy lists use human feature names in English and Arabic', async ({ page }) => {
  const accounts = JSON.parse(await readFile('.local/synthetic-accounts.json', 'utf8')) as Account[];
  const admin = accounts.find(row => row.role === 'admin'); if (!admin) throw Error('Synthetic administrator required.');
  await page.goto('/'); await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.getByLabel('School email').fill(admin.email); await page.getByLabel('Password', { exact: true }).fill(admin.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByText('School access verified', { exact: true })).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: 'Access details', exact: true }).click();
  await expect(page.locator('.capability-list')).toContainText('Learning progress');
  await expect(page.locator('.capability-list')).toContainText('School operations');
  expect(await page.locator('.capability-list').innerText()).not.toContain('learner.state');
  await page.setViewportSize({ width: 390, height: 844 }); await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await expect(page.locator('.capability-list')).toContainText('تقدّم التعلّم');
  await expect(page.locator('.capability-list')).toContainText('إدارة المدرسة');
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.getByRole('navigation').getByRole('button', { name: 'School', exact: true }).click();
  await page.getByRole('button', { name: 'Policies', exact: true }).click();
  const table = page.getByRole('table').filter({ hasText: 'Learning progress' });
  await expect(table).toContainText('Learning progress');
  expect(await table.innerText()).not.toContain('school.operations');
  await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await expect(page.getByRole('table').filter({ hasText: 'تقدّم التعلّم' })).toContainText('إدارة المدرسة');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([]);
});
