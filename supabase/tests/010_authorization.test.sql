-- These tests exercise role grants and real row visibility under the same transaction context as the API.
begin;
create extension if not exists pgtap with schema extensions;
grant usage on schema extensions to cuevo_api,anon,authenticated;
set local search_path = extensions, pg_catalog;
select no_plan();
set local role anon;
select throws_ok('select * from app.people', '42501', null, 'anonymous cannot reach learner data');
reset role;
set local role authenticated;
select throws_ok('select * from app.people', '42501', null, 'Data API authenticated role cannot reach learner data');
reset role;

set local role cuevo_api;
select is((select count(*) from app.people),0::bigint,'missing actor and school context returns no people');
select set_config('app.actor_id','20000000-0000-4000-8000-000000000012',true);
select is((select count(*) from "authorization".current_memberships()),1::bigint,'bootstrap sees only verified actor memberships without school context');
select set_config('app.school_id','10000000-0000-4000-8000-000000000001',true);
select is((select count(*) from app.people),1::bigint,'student sees self only');
select is((select count(*) from app.memberships),1::bigint,'student sees only own membership');
select is((select count(*) from app.classes),1::bigint,'student sees enrolled class only');
select is((select count(*) from app.enrollments),1::bigint,'student sees own enrollment only');
select is((select count(*) from app.people where actor_id='20000000-0000-4000-8000-000000000013'),0::bigint,'student cannot enumerate peer');
select set_config('app.school_id','10000000-0000-4000-8000-000000000002',true);
select is((select count(*) from app.people),0::bigint,'forged school context yields no protected rows');
select set_config('app.school_id','10000000-0000-4000-8000-000000000001',true);
select throws_ok($$update app.people set display_name='tampered' where actor_id='20000000-0000-4000-8000-000000000012'$$,'42501',null,'student cannot mutate authoritative profile');

select set_config('app.actor_id','20000000-0000-4000-8000-000000000072',true);
select is((select count(*) from app.people),2::bigint,'parent sees self and current related child');
select is((select count(*) from app.people where actor_id='20000000-0000-4000-8000-000000000013'),0::bigint,'parent cannot see unrelated child');
select is((select count(*) from app.classes),1::bigint,'parent sees related child class');
reset role;
update app.parent_relationships set status='revoked' where parent_actor_id='20000000-0000-4000-8000-000000000072';
set local role cuevo_api;
select is((select count(*) from app.people),1::bigint,'revoked parent relationship immediately removes child access');
select is((select count(*) from app.classes),0::bigint,'revoked parent loses child class access');
reset role;
update app.parent_relationships set status='active',effective_to=now()-interval '1 second' where parent_actor_id='20000000-0000-4000-8000-000000000072';
set local role cuevo_api;
select is((select count(*) from app.people),1::bigint,'expired parent relationship cannot grant access');

select set_config('app.actor_id','20000000-0000-4000-8000-000000000004',true);
select is((select count(*) from app.people),11::bigint,'teacher sees self and ten assigned class learners');
select is((select count(*) from app.classes),1::bigint,'teacher sees assigned class only');
select is((select count(*) from app.people where actor_id='20000000-0000-4000-8000-000000000013'),0::bigint,'teacher cannot see unassigned class learner');
reset role;
update app.teacher_assignments set status='revoked' where teacher_actor_id='20000000-0000-4000-8000-000000000004';
set local role cuevo_api;
select is((select count(*) from app.people),1::bigint,'revoked teacher assignment immediately removes learners');
select is((select count(*) from app.classes),0::bigint,'revoked teacher cannot query class');

select set_config('app.actor_id','20000000-0000-4000-8000-000000000002',true);
select is((select count(*) from app.people),131::bigint,'coordinator sees current school directory');
select is((select count(*) from app.classes),6::bigint,'coordinator sees school classes');
select set_config('app.actor_id','20000000-0000-4000-8000-000000000001',true);
select is((select count(*) from app.people),131::bigint,'admin sees current school directory');
select is((select count(*) from app.people where school_id='10000000-0000-4000-8000-000000000002'),0::bigint,'admin has no second-tenant access');
reset role;
update app.entitlements set enabled=false where school_id='10000000-0000-4000-8000-000000000001' and code='school.context';
set local role cuevo_api;
select is((select count(*) from app.people),0::bigint,'disabled entitlement denies protected data');
select is((select count(*) from "authorization".current_memberships()),1::bigint,'actor may inspect membership when entitlement is disabled');
reset role;
update app.entitlements set enabled=true where school_id='10000000-0000-4000-8000-000000000001' and code='school.context';
update app.memberships set status='suspended' where school_id='10000000-0000-4000-8000-000000000001' and actor_id='20000000-0000-4000-8000-000000000001';
set local role cuevo_api;
select is((select count(*) from app.people),0::bigint,'suspended actor loses all protected rows');
select is((select count(*) from "authorization".current_memberships()),0::bigint,'suspended actor cannot bootstrap membership');
select set_config('app.actor_id','not-a-uuid',true);
select is((select count(*) from app.people),0::bigint,'malformed actor context fails closed');
reset role;
select throws_ok($$insert into app.enrollments(school_id,class_id,student_actor_id) values ('10000000-0000-4000-8000-000000000002','30000000-0000-4000-8000-000000000001','20000000-0000-4000-8000-000000000133')$$,'23503',null,'composite foreign key prevents cross-school enrollment');
select throws_ok($$insert into app.parent_relationships(school_id,parent_actor_id,student_actor_id,relationship_type) values ('10000000-0000-4000-8000-000000000002','20000000-0000-4000-8000-000000000072','20000000-0000-4000-8000-000000000133','guardian')$$,'23503',null,'composite foreign key prevents cross-school guardian link');
select * from finish();
rollback;
