-- A cached JWT must not retain protected API access after its authoritative session disappears.
begin;
create extension if not exists pgtap with schema extensions;
grant usage on schema extensions to cuevo_api;
set local search_path = extensions, pg_catalog;
select no_plan();
insert into auth.users(id) values ('20000000-0000-4000-8000-000000000001'),('20000000-0000-4000-8000-000000000012') on conflict(id) do nothing;
insert into auth.sessions(id,user_id,created_at,updated_at,not_after) values ('80000000-0000-4000-8000-000000000001','20000000-0000-4000-8000-000000000001',now(),now(),now()+interval '15 minutes');
set local role cuevo_api;
select set_config('app.actor_id','20000000-0000-4000-8000-000000000001',true);
select is("authorization".is_current_session('80000000-0000-4000-8000-000000000001'),true,'current actor session is authorized');
select set_config('app.actor_id','20000000-0000-4000-8000-000000000012',true);
select is("authorization".is_current_session('80000000-0000-4000-8000-000000000001'),false,'another actor cannot reuse session id');
select set_config('app.actor_id','20000000-0000-4000-8000-000000000001',true);
reset role;
update auth.sessions set not_after=now()-interval '1 second' where id='80000000-0000-4000-8000-000000000001';
set local role cuevo_api;
select is("authorization".is_current_session('80000000-0000-4000-8000-000000000001'),false,'expired session is denied');
reset role;
update auth.sessions set not_after=now()+interval '15 minutes' where id='80000000-0000-4000-8000-000000000001';
update auth.users set banned_until=now()+interval '1 hour' where id='20000000-0000-4000-8000-000000000001';
set local role cuevo_api;
select is("authorization".is_current_session('80000000-0000-4000-8000-000000000001'),false,'banned auth user cannot use current session');
reset role;
update auth.users set banned_until=null where id='20000000-0000-4000-8000-000000000001';
delete from auth.sessions where id='80000000-0000-4000-8000-000000000001';
set local role cuevo_api;
select is("authorization".is_current_session('80000000-0000-4000-8000-000000000001'),false,'revoked session is denied immediately');
select is("authorization".is_current_session(null),false,'missing session id fails closed');
reset role;
select * from finish();
rollback;
