-- Read-time setup status never enables runtime, reveals recipients or creates effects.
begin;
create extension if not exists pgtap with schema extensions;
grant usage on schema extensions to cuevo_api,cuevo_worker;
set local search_path=extensions,pg_catalog;
select no_plan();
select internal.configure_worker_dispatch(false,null,null,false);
select set_config('app.runtime_env','local',true);
select ok(has_function_privilege('cuevo_api','internal.read_school_account_availability()','EXECUTE'),'API has only the protected availability entrypoint');
select ok(not exists(select 1 from pg_roles role where role.rolname in('anon','authenticated','service_role','cuevo_worker')and has_function_privilege(role.oid,'internal.read_school_account_availability()','EXECUTE')),'worker and Data API roles cannot read setup status');
select ok(not exists(select 1 from pg_proc p cross join lateral aclexplode(coalesce(p.proacl,acldefault('f',p.proowner)))permission where p.oid='internal.read_school_account_availability()'::regprocedure and permission.grantee=0 and permission.privilege_type='EXECUTE'),'PUBLIC has no availability execute');
select set_config('app.actor_id','20000000-0000-4000-8000-000000000001',true);
select set_config('app.school_id','10000000-0000-4000-8000-000000000001',true);
set local role cuevo_api;
select is(internal.read_school_account_availability(),' {"state":"SETUP_REQUIRED","reason":"OPERATOR_APPROVAL_REQUIRED"}'::jsonb,'disabled runtime provides a truthful setup-required read');
select throws_ok($$select internal.read_school_account_invitations(25,null)$$,'42501',null,'setup status never weakens disabled invitation reads');
select set_config('app.actor_id','20000000-0000-4000-8000-000000000004',true);
select throws_ok($$select internal.read_school_account_availability()$$,'42501',null,'teacher cannot read administrator setup');
select set_config('app.actor_id','20000000-0000-4000-8000-000000000001',true);
select set_config('app.school_id','10000000-0000-4000-8000-000000000002',true);
select throws_ok($$select internal.read_school_account_availability()$$,'42501',null,'foreign school scope is denied before setup projection');
reset role;
select set_config('app.school_id','10000000-0000-4000-8000-000000000001',true);
select internal.configure_local_school_account_runtime(true,(select oid from pg_catalog.pg_database where datname=current_database()),'LOCAL_CUEVO','20000000-0000-4000-8000-000000000001','Rollback availability approval',(select revision from internal.school_account_runtime_control where singleton),true);
set local role cuevo_api;
select is(internal.read_school_account_availability(),' {"state":"AVAILABLE","reason":null}'::jsonb,'current exact operator approval is available without an account effect');
reset role;
select ok((select enabled from internal.school_account_runtime_control where singleton),'read preserved explicit approval');
select * from finish();
rollback;
